import assert from 'node:assert/strict';
import {usableSetSnapshot,reviewedAnnualFallback,chooseFreeSources,applyFreeHeadlineFallback} from '../server/free-data-fallback.js';
import {currentMultiples} from '../server/screener-run.js';
const at=new Date('2026-11-12T12:00:00Z');
const fin={symbol:'SET:TEST',price:100,priceDate:'2026-11-12',years:[{eps:10}],ttm:{eps:5,epsAsOf:'2026-06-30',bvps:50,bvpsAsOf:'2026-06-30'}};
const official={asOf:'2026-11-11',pe:{value:18},pbv:{value:2},de:{value:1},dividendYield:{value:4},annualYears:[]};
assert(usableSetSnapshot(official,at));
assert(!usableSetSnapshot({...official,asOf:'2026-01-01'},at));
assert(!usableSetSnapshot({...official,asOf:'2027-01-01'},at));
assert.equal(applyFreeHeadlineFallback({},fin,official,at).pe,18);
const fallback=applyFreeHeadlineFallback({recurringDividendYield:.03},fin,null,at);
assert.equal(fallback.pe,20);assert.equal(fallback.pbv,2);assert.equal(fallback.de,null);
assert.equal(fallback.dividendYield,.03);assert.equal(fallback.ratioSource,'calculated-provider');
assert.equal(applyFreeHeadlineFallback({}, {...fin,ttm:{...fin.ttm,eps:-1}},null,at).pe,null);
assert.equal(applyFreeHeadlineFallback({}, {...fin,ttm:{eps:5}},null,at).pe,null);
assert.equal(applyFreeHeadlineFallback({}, {...fin,ttm:{eps:5,epsAsOf:'2020-01-01'}},null,at).pe,null);
const rows=[{fiscalYear:2024,asOf:'2024-12-31',publishedAt:'2025-03-01',openingEquity:100,equity:100,netIncome:10},{fiscalYear:2025,asOf:'2025-12-31',publishedAt:'2026-03-01',openingEquity:100,equity:120,netIncome:11},{fiscalYear:2026,asOf:'2026-12-31',publishedAt:'2027-03-01'}];
const reviewed=reviewedAnnualFallback(rows,at);
assert.equal(reviewed.length,2);assert.equal(reviewed[1].roe,.1);
assert.equal(reviewedAnnualFallback(rows.slice(0,1),at).length,0);
assert.equal(chooseFreeSources(fin,null,rows,at).qualitySource,'sec-reviewed-calculated');
assert.equal(chooseFreeSources(fin,null,[],at).qualitySource,'provider-statements');
assert.equal(chooseFreeSources(fin,official,rows,at).qualitySource,'set.or.th');
assert.equal(currentMultiples({...fin,sourceFallback:true,ttm:{eps:-1}}).peCurrent,null);
